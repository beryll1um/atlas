namespace {

// It's not the wisest solution, but at least it provides a friendly interface.
template <atl::ByteLike T, std::size_t N>
bool operator==(const std::vector<T>& vec, const char (&str)[N]) {
	return vec.size() == N - 1 && std::equal(vec.begin(), vec.end(), reinterpret_cast<const T*>(str));
}

template <atl::ByteLike T>
void FromStringTestImpl() {
	EXPECT_TRUE(atl::base58::FromString<T>("") == "");
	EXPECT_TRUE(atl::base58::FromString<T>("2g") == "\x61");
	EXPECT_TRUE(atl::base58::FromString<T>("a3gV") == "\x62\x62\x62");
	EXPECT_TRUE(atl::base58::FromString<T>("aPEr") == "\x63\x63\x63");
	EXPECT_TRUE(atl::base58::FromString<T>("2cFupjhnEsSn59qHXstmK2ffpLv2") ==
		"\x73\x69\x6d\x70\x6c\x79\x20\x61\x20\x6c\x6f\x6e\x67\x20\x73\x74\x72\x69\x6e\x67");
	EXPECT_TRUE(atl::base58::FromString<T>("1NS17iag9jJgTHD1VXjvLCEnZuQ3rJDE9L") ==
		"\x00\xeb\x15\x23\x1d\xfc\xeb\x60\x92\x58\x86\xb6\x7d\x06\x52\x99\x92\x59\x15\xae\xb1\x72\xc0\x66\x47");
	EXPECT_TRUE(atl::base58::FromString<T>("ABnLTmg") == "\x51\x6b\x6f\xcd\x0f");
	EXPECT_TRUE(atl::base58::FromString<T>("3SEo3LWLoPntC") == "\xbf\x4f\x89\x00\x1e\x67\x02\x74\xdd");
	EXPECT_TRUE(atl::base58::FromString<T>("3EFU7m") == "\x57\x2e\x47\x94");
	EXPECT_TRUE(atl::base58::FromString<T>("EJDM8drfXA6uyA") == "\xec\xac\x89\xca\xd9\x39\x23\xc0\x23\x21");
	EXPECT_TRUE(atl::base58::FromString<T>("Rt5zm") == "\x10\xc8\x51\x1e");
	EXPECT_TRUE(atl::base58::FromString<T>("1111111111") == "\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
	EXPECT_TRUE(atl::base58::FromString<T>("1111111111111111111111111111111111111111") ==
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00");
	EXPECT_TRUE(atl::base58::FromString<T>("1111111111111111111111111111111111111112") ==
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x01");
	EXPECT_TRUE(
		atl::base58::FromString<T>(
			"1111111111111111111111111111111111111111111111111111"
			"11111111111111111111111111111111115TYzLYH1udmLdzCLM"
		) ==
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
		"\x00\x00\x00\x00\x00\x00\xec\x39\xd0\x4c\x37\xe7\x1e\x5d\x59\x18\x81\xf6"
	);
	EXPECT_TRUE(atl::base58::FromString<T>("123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz") ==
		"\x00\x01\x11\xd3\x8e\x5f\xc9\x07\x1f\xfc\xd2\x0b\x4a\x76\x3c\xc9\xae\x4f\x25\x2b\xb4"
		"\xe4\x8f\xd6\x6a\x83\x5e\x25\x2a\xda\x93\xff\x48\x0d\x6d\xd4\x3d\xc6\x2a\x64\x11\x55\xa5");
	EXPECT_TRUE(
		atl::base58::FromString<T>(
			"1cWB5HCBdLjAuqGGReWE3R3CguuwSjw6RHn39s2yuDRTS5NsBgNiFpWgAnEx6VQi8csexkgYw3mdYrMHr8x9i7aEwP"
			"8kZ7vccXWqKDvGv3u1GxFKPuAkn8JCPPGDMf3vMMnbzm6Nh9zh1gcNsMvH3ZNLmP5fSG6DGbbi2tuwMWPthr4boWwC"
			"xf7ewSgNQeacyozhKDDQQ1qL5fQFUW52QKUZDZ5fw3KXNQJMcNTcaB723LchjeKun7MuGW5qyCBZYzA1KjofN1gYBV"
			"3NqyhQJ3Ns746GNuf9N2pQPmHz4xpnSrrfCvy6TVVz5d4PdrjeshsWQwpZsZGzvbdAdN8MKV5QsBDY"
		) ==
		"\x00\x01\x02\x03\x04\x05\x06\x07\x08\x09\x0a\x0b\x0c\x0d\x0e\x0f\x10\x11\x12\x13\x14\x15\x16\x17"
		"\x18\x19\x1a\x1b\x1c\x1d\x1e\x1f\x20\x21\x22\x23\x24\x25\x26\x27\x28\x29\x2a\x2b\x2c\x2d\x2e\x2f"
		"\x30\x31\x32\x33\x34\x35\x36\x37\x38\x39\x3a\x3b\x3c\x3d\x3e\x3f\x40\x41\x42\x43\x44\x45\x46\x47"
		"\x48\x49\x4a\x4b\x4c\x4d\x4e\x4f\x50\x51\x52\x53\x54\x55\x56\x57\x58\x59\x5a\x5b\x5c\x5d\x5e\x5f"
		"\x60\x61\x62\x63\x64\x65\x66\x67\x68\x69\x6a\x6b\x6c\x6d\x6e\x6f\x70\x71\x72\x73\x74\x75\x76\x77"
		"\x78\x79\x7a\x7b\x7c\x7d\x7e\x7f\x80\x81\x82\x83\x84\x85\x86\x87\x88\x89\x8a\x8b\x8c\x8d\x8e\x8f"
		"\x90\x91\x92\x93\x94\x95\x96\x97\x98\x99\x9a\x9b\x9c\x9d\x9e\x9f\xa0\xa1\xa2\xa3\xa4\xa5\xa6\xa7"
		"\xa8\xa9\xaa\xab\xac\xad\xae\xaf\xb0\xb1\xb2\xb3\xb4\xb5\xb6\xb7\xb8\xb9\xba\xbb\xbc\xbd\xbe\xbf"
		"\xc0\xc1\xc2\xc3\xc4\xc5\xc6\xc7\xc8\xc9\xca\xcb\xcc\xcd\xce\xcf\xd0\xd1\xd2\xd3\xd4\xd5\xd6\xd7"
		"\xd8\xd9\xda\xdb\xdc\xdd\xde\xdf\xe0\xe1\xe2\xe3\xe4\xe5\xe6\xe7\xe8\xe9\xea\xeb\xec\xed\xee\xef"
		"\xf0\xf1\xf2\xf3\xf4\xf5\xf6\xf7\xf8\xf9\xfa\xfb\xfc\xfd\xfe\xff");
	EXPECT_TRUE(atl::base58::FromString<T>("zzzzy") == "\x27\x1f\x35\x9e");
	EXPECT_TRUE(atl::base58::FromString<T>("zzzzz") == "\x27\x1f\x35\x9f");
	EXPECT_TRUE(atl::base58::FromString<T>("211111") == "\x27\x1f\x35\xa0");
	EXPECT_TRUE(atl::base58::FromString<T>("211112") == "\x27\x1f\x35\xa1");
	EXPECT_TRUE(
		atl::base58::FromString<T>("4oR3Swwh73RycXGBUgXPd77TNqp3B8utzQxY5wn2Kgum") ==
		"\x38\x76\xf6\x6c\x92\x63\xf0\xa0\xeb\x73\x6c\x30\x41\x07\x3b\x64"
		"\x95\x32\x10\x10\x08\x88\xdb\x9d\xbe\xb1\xee\x23\x8c\x20\x41\xf0"
	);
	EXPECT_TRUE(
		atl::base58::FromString<T>("HXHsRLzfhV52jyHYHjKbvin8PRGjLYT3B6U9heqo4kdR") ==
		"\xf5\x7d\x7d\x41\x5f\xa7\x3d\x14\x28\xf3\xc2\xee\x52\xbb\x71\x1b"
		"\x04\x92\xa3\xba\xc6\x48\xd4\x4f\xfe\x4b\x55\xe3\xb9\xab\xc7\xe4"
	);
	EXPECT_TRUE(
		atl::base58::FromString<T>("11111111111111111111111111111111") ==
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
		"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
	);
	EXPECT_TRUE(
		atl::base58::FromString<T>("ComputeBudget111111111111111111111111111111") ==
		"\x03\x06\x46\x6f\xe5\x21\x17\x32\xff\xec\xad\xba\x72\xc3\x9b\xe7"
		"\xbc\x8c\xe5\xbb\xc5\xf7\x12\x6b\x2c\x43\x9b\x3a\x40\x00\x00\x00"
	);
	EXPECT_TRUE(
		atl::base58::FromString<T>("HDwcJBJXjL9FpJ7UBsYBtaDjsBUhuLCUYoz3zr8SWWaQ") ==
		"\xf1\x0b\xb4\xe5\x0d\x56\xfd\xa1\x3d\xfe\x1f\x32\x9b\x8d\x39\x3d"
		"\xd2\x4a\x01\x45\x91\xe1\x83\x16\x97\x94\x0d\x7c\x34\xa3\x8d\xdd"
	);
}

}  // namespace

TEST(Base58, FromString) {
	FromStringTestImpl<char>();
	FromStringTestImpl<unsigned char>();
	FromStringTestImpl<std::byte>();
}

